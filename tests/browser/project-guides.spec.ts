import {test,expect} from '@playwright/test';
import {fixtureArchive,fixtureMarket} from '../fixture';

test.beforeEach(async({page})=>{
  await page.clock.install({time:new Date('2026-11-02T05:00:00Z')});
  await page.route('**/data/archive.json',r=>r.fulfill({json:fixtureArchive}));
  await page.route('**/data/market.json',r=>r.fulfill({json:fixtureMarket}));
  await page.route('**/api/data*',r=>r.fulfill({json:{archive:fixtureArchive}}));
  await page.route('https://tds-network-games.sanand.workers.dev/prediction-market/api/markets',r=>r.fulfill({json:{markets:[fixtureMarket]}}));
});
test('the homepage shows all question descriptions and deadlines, then opens separate guides',async({page})=>{
  const requests:string[]=[];page.on('request',r=>requests.push(r.url()));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'One project. Seven questions.',exact:true})).toBeVisible();
  await expect(page.locator('.home-question')).toHaveCount(7);
  await expect(page.locator('.home-question').filter({has:page.getByRole('heading',{name:'Picture Stories',exact:true})})).toContainText('29 October, noon');
  expect(requests.some(url=>url.includes('/data/archive.json')||url.includes('/prediction-market/api'))).toBe(false);
  await page.locator('.home-question[href="#q2"]').click();
  await expect(page).toHaveURL(/#q2$/);
  await expect(page.getByRole('heading',{name:'Record your Human Exchange offer',exact:true})).toBeVisible();
  await expect(page.locator('.home-question')).toHaveCount(0);
  await expect(page.locator('.tabs')).toHaveCount(0);
  await expect(page.locator('.phase-status')).toHaveText('Within published window');
  await page.getByRole('link',{name:'← All P1 questions',exact:true}).click();
  await page.locator('.home-question[href="#q3"]').click();
  await expect(page.locator('.phase-status')).toHaveText('Published window closed');
  await expect(page.locator('.question-guide')).toContainText('without AI agents');
  await page.goto('/#q7');
  await expect(page.getByRole('heading',{name:'Picture Stories',exact:true})).toBeVisible();
  await expect(page.locator('.phase-status.closed')).toHaveCount(2);
  await page.reload();
  await expect(page.getByRole('heading',{name:'Picture Stories',exact:true})).toBeVisible();
  await page.goto('/#q6');
  await expect(page.locator('.phase-status.check-game')).toHaveCount(2);
  await expect(page.locator('.question-guide')).toContainText('Do not assume the whole of November 2 remains open.');
  expect(requests.some(url=>url.includes('/data/archive.json')||url.includes('/prediction-market/api'))).toBe(false);
});
test('Q1 opens the existing solver and guide and preserves an edited draft on homepage navigation',async({page})=>{
  await page.goto('/');
  await page.locator('.home-question[href="#forecast"]').click();
  await expect(page.getByRole('button',{name:'Copy reason',exact:true})).toBeEnabled();
  await expect(page.getByRole('button',{name:'Other P1 questions',exact:true})).toHaveCount(0);
  const edited='My edited Q1 explanation survives navigating to another question.';
  await page.locator('#home-reason').fill(edited);
  await page.getByRole('button',{name:'How to play',exact:true}).click();
  await expect(page.getByRole('heading',{name:'What is the prediction game?',exact:true})).toBeVisible();
  await page.getByRole('link',{name:'← All P1 questions',exact:true}).click();
  await page.locator('.home-question[href="#q2"]').click();
  await page.getByRole('link',{name:'← All P1 questions',exact:true}).click();
  await page.locator('.home-question[href="#forecast"]').click();
  await expect(page.locator('#home-reason')).toHaveValue(edited);
  await page.goBack();
  await expect(page.getByRole('heading',{name:'One project. Seven questions.',exact:true})).toBeVisible();
});
test('the Q2 helper edits scripts and times rehearsal without recording or submissions',async({page})=>{
  await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{value:{writeText:async()=>{throw new Error('blocked')}}});});
  const posts:string[]=[];page.on('request',r=>{if(r.method()==='POST')posts.push(r.url());});
  await page.goto('/#q2');
  await expect(page.locator('.offer-script')).toContainText('test a classmate’s website');
  await page.locator('#offer-service').fill('review a classmate’s chart');
  await expect(page.locator('.offer-script')).toContainText('I offer to review a classmate’s chart.');
  await page.getByRole('button',{name:'Copy offer script',exact:true}).click();
  await expect(page.getByText('Copy was blocked. Select the script below and copy it manually.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Start rehearsal',exact:true}).click();
  await page.clock.fastForward(5000);
  await expect(page.getByText('55 seconds remaining',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Pause rehearsal',exact:true}).click();
  await page.clock.fastForward(5000);
  await expect(page.getByText('55 seconds remaining',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Reset timer',exact:true}).click();
  await expect(page.getByText('60 seconds remaining',{exact:true})).toBeVisible();
  await page.locator('#offer-service').fill('');
  await expect(page.getByRole('alert')).toContainText('Fill every field');
  expect(await page.evaluate(()=>localStorage.length+sessionStorage.length)).toBe(0);
  expect(posts).toEqual([]);
});
